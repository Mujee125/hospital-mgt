//! Per-client database seat provisioning (server-build / integration-test only).
//!
//! ROOT CAUSE (2026-10 security audit): the previous pairing flow handed every
//! client the SERVER'S OWN `postgres` superuser credentials. Any paired
//! workstation therefore held unrestricted superuser access to the entire PHI
//! store, could bypass every application-layer security control via a direct
//! `psql` connection, and the server had no way to count, identify, or revoke
//! a device.
//!
//! This module closes that hole:
//!   1. Ensures an unprivileged base role `hms_app_client` (NOSUPERUSER,
//!      NOCREATEDB, NOCREATEROLE) that owns only DML privileges on the app
//!      schema.
//!   2. Mints a dedicated per-device login role `hms_client_<uuid>` (member of
//!      the base role, `CONNECTION LIMIT 10`) with a high-entropy random
//!      password generated by `OsRng`.
//!   3. Registers the device in `client_devices`, enforcing the signed seat cap
//!      and reclaiming the existing seat on re-pair (NFR-31 idempotency).
//!   4. Provides revoke / replace, which flip the role to `NOLOGIN` so a
//!      revoked workstation can no longer authenticate at the database.
//!
//! Clinical-safety invariant: seat limits gate the PAIRING of new devices and
//! (optionally) concurrent sessions only. They never block read access to
//! existing patient data for an already-paired, already-logged-in clinician.
//!
//! NOTE on `CREATE ROLE` / `GRANT`: these cannot use bind parameters (DDL, not
//! DML). Every interpolated value is either a module constant (`hms_app_client`)
//! or a device-derived identifier passed through `sanitize_device_role` +
//! `crate::db::validate_db_identifier` (ASCII allow-list, <=63 chars). Passwords
//! are hex-only (no quote-injection risk).

use rand::RngCore;
use sqlx::PgPool;
use tauri::Manager;
use uuid::Uuid;

/// Unprivileged base role that owns DML privileges on the application schema.
pub const BASE_ROLE: &str = "hms_app_client";
/// Per-device role name prefix. Full role is `hms_client_<uuid>` with hyphens
/// replaced by underscores (Postgres unquoted-identifier rule).
const CLIENT_ROLE_PREFIX: &str = "hms_client_";
/// Per-device connection cap (defense-in-depth alongside the app-layer cap).
const CONNECTION_LIMIT: &str = "10";

/// Request describing the client device being paired.
pub struct SeatRequest<'a> {
    /// Stable per-install UUID minted by the client on first run.
    pub device_id: &'a str,
    /// Client's hardware fingerprint (CPU/baseboard/BIOS hash) — seat-reuse key.
    pub device_fingerprint: &'a str,
    /// Operator-friendly label ("Reception PC 2"). Cosmetic only.
    pub device_name: &'a str,
    /// Source IP of the TLS pairing connection. Recorded as `last_seen_ip`
    /// (the registry's own DB connection is always loopback, so
    /// `inet_client_addr()` would be useless here).
    pub peer_ip: Option<std::net::IpAddr>,
}

/// Fresh credential + seat identity returned to the pairing listener.
pub struct ProvisionedSeat {
    /// The per-device database role the client must authenticate as.
    pub db_role: String,
    /// The role's freshly-minted password (plaintext, sent once over the TLS
    /// pairing channel; the client stores it DPAPI-encrypted).
    pub db_password: String,
    /// The device's UUID, echoed back so the client can pin its identity.
    pub device_id: String,
}

/// Seat provisioning failure. `Exhausted` carries counts so the pairing
/// listener can return an operator-actionable `seat_limit_reached` error.
pub enum SeatError {
    /// Signed seat cap reached — active == max non-revoked devices.
    Exhausted { active: i64, max: u32 },
    /// Any other failure (empty identity, DDL error, registry error, ...).
    Other(String),
}

/// Derive the per-device role name from a device UUID.
///
/// Rejects anything that is not a canonical UUID, replaces hyphens with
/// underscores, prefixes it, and validates against the shared allow-list.
/// Guarantees a safe identifier with no quote-injection surface.
fn sanitize_device_role(device_id: &str) -> Result<String, SeatError> {
    let compact = device_id.trim().replace('-', "_");
    if compact.is_empty()
        || !compact
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_')
    {
        return Err(SeatError::Other(format!(
            "device_id is not a valid UUID: {:?}",
            device_id
        )));
    }
    let role = format!("{}{}", CLIENT_ROLE_PREFIX, compact);
    crate::db::validate_db_identifier(&role).map_err(SeatError::Other)?;
    Ok(role)
}

/// Generate a high-entropy random password using the OS CSPRNG.
///
/// 32 random bytes hex-encoded = 64 chars from `[0-9a-f]`. Hex-only means the
/// value can never contain a single quote, so it is safe to interpolate into a
/// `PASSWORD '...'` literal without escaping.
fn generate_password() -> String {
    let mut buf = [0u8; 32];
    rand::rngs::OsRng.fill_bytes(&mut buf);
    hex::encode(buf)
}

/// Ensure the unprivileged base role exists with the correct privileges.
///
/// Idempotent: `CREATE ROLE` runs only when the role is absent; every `GRANT`
/// is naturally idempotent. Must run as a superuser (the app connects as
/// `postgres`), which is why this lives in the server build.
async fn ensure_base_role(pool: &PgPool) -> Result<(), SeatError> {
    let exists: Option<i32> = sqlx::query_scalar("SELECT 1 FROM pg_roles WHERE rolname = $1")
        .bind(BASE_ROLE)
        .fetch_optional(pool)
        .await
        .map_err(|e| SeatError::Other(format!("check base role: {}", e)))?;

    if exists.is_none() {
        let create = format!(
            "CREATE ROLE {base} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE \
             NOINHERIT NOREPLICATION NOBYPASSRLS",
            base = BASE_ROLE
        );
        sqlx::query(&create)
            .execute(pool)
            .await
            .map_err(|e| SeatError::Other(format!("create base role: {}", e)))?;
    }

    // DML privileges on the application schema. Idempotent, and also covers
    // tables created after the base role via ALTER DEFAULT PRIVILEGES.
    //
    // Two latent-bug fixes (2026-10 seat-registry work):
    //  1. `GRANT ... ON DATABASE current_database()` is INVALID SQL — GRANT
    //     takes a database *identifier*, not an expression, so the old
    //     string was a guaranteed syntax error the first time a pairing
    //     ever reached provisioning. Resolve the connected database name
    //     first and quote it (validated by `validate_db_identifier`).
    //  2. sqlx's `query()` prepares its statement, and PostgreSQL's
    //     extended-query protocol rejects multi-statement strings
    //     ("cannot insert multiple commands into a prepared statement").
    //     Each statement is therefore executed separately.
    let dbname: String = sqlx::query_scalar("SELECT current_database()")
        .fetch_one(pool)
        .await
        .map_err(|e| SeatError::Other(format!("resolve database name: {}", e)))?;
    crate::db::validate_db_identifier(&dbname).map_err(SeatError::Other)?;

    let base = BASE_ROLE;
    let statements = [
        format!("GRANT CONNECT ON DATABASE \"{dbname}\" TO {base}"),
        format!("GRANT USAGE ON SCHEMA public TO {base}"),
        format!("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO {base}"),
        format!("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO {base}"),
        format!(
            "ALTER DEFAULT PRIVILEGES IN SCHEMA public \
             GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {base}"
        ),
        format!(
            "ALTER DEFAULT PRIVILEGES IN SCHEMA public \
             GRANT USAGE, SELECT ON SEQUENCES TO {base}"
        ),
    ];
    for stmt in &statements {
        sqlx::query(stmt)
            .execute(pool)
            .await
            .map_err(|e| SeatError::Other(format!("grant base privileges ({}): {}", stmt, e)))?;
    }

    Ok(())
}

/// Create or reset a per-device login role with the given password.
///
/// Idempotent on the role name: if the role already exists (re-pair, or
/// replace), `ALTER` it back to a login-capable, limited role and set the new
/// password rather than failing on `CREATE`.
async fn upsert_client_role(pool: &PgPool, role: &str, password: &str) -> Result<(), SeatError> {
    let exists: Option<i32> = sqlx::query_scalar("SELECT 1 FROM pg_roles WHERE rolname = $1")
        .bind(role)
        .fetch_optional(pool)
        .await
        .map_err(|e| SeatError::Other(format!("check client role: {}", e)))?;

    // Role names are validated identifiers; password is hex-only. Safe to
    // interpolate into DDL.
    //
    // Latent-bug fix (2026-10): the ALTER branch used to repeat
    // `IN ROLE {base}`, which is NOT idempotent — re-pairing a device whose
    // role already holds the membership can error ("already a member of
    // role") and the seat rotation then fails. Membership is now granted
    // once by the separate, idempotent `GRANT` below (GRANT on an existing
    // membership is a no-op NOTICE), so CREATE/ALTER carry only attributes.
    let stmt = if exists.is_some() {
        format!(
            "ALTER ROLE {role} LOGIN \
             NOSUPERUSER NOCREATEDB NOCREATEROLE \
             CONNECTION LIMIT {lim} PASSWORD '{pw}'",
            role = role,
            lim = CONNECTION_LIMIT,
            pw = password
        )
    } else {
        format!(
            "CREATE ROLE {role} LOGIN \
             NOSUPERUSER NOCREATEDB NOCREATEROLE \
             CONNECTION LIMIT {lim} PASSWORD '{pw}'",
            role = role,
            lim = CONNECTION_LIMIT,
            pw = password
        )
    };
    sqlx::query(&stmt)
        .execute(pool)
        .await
        .map_err(|e| SeatError::Other(format!("provision client role: {}", e)))?;

    // Idempotent base-role membership (see the note above). `role` came from
    // `sanitize_device_role` → `validate_db_identifier`; `base` is a
    // module constant — neither can inject SQL.
    let grant = format!("GRANT {base} TO {role}", base = BASE_ROLE, role = role);
    sqlx::query(&grant)
        .execute(pool)
        .await
        .map_err(|e| SeatError::Other(format!("grant base membership: {}", e)))?;
    Ok(())
}

/// Count currently-active (non-revoked) registered client devices.
async fn active_seat_count(pool: &PgPool) -> Result<i64, SeatError> {
    sqlx::query_scalar("SELECT COUNT(*) FROM client_devices WHERE revoked_at IS NULL")
        .fetch_one(pool)
        .await
        .map_err(|e| SeatError::Other(format!("count active seats: {}", e)))
}

// ── Provisioning / revocation ─────────────────────────────────────────────────

/// Look up the active seat for a hardware fingerprint (the seat-reuse key).
/// Returns `(device_id, db_role)` of the matching active device, if any.
async fn find_active_by_fingerprint(
    pool: &PgPool,
    fingerprint: &str,
) -> Result<Option<(uuid::Uuid, String)>, SeatError> {
    sqlx::query_as(
        "SELECT device_id, db_role FROM client_devices \
         WHERE hardware_fingerprint = $1 AND revoked_at IS NULL \
         LIMIT 1",
    )
    .bind(fingerprint)
    .fetch_optional(pool)
    .await
    .map_err(|e| SeatError::Other(format!("find seat by fingerprint: {}", e)))
}

/// Look up the active seat registered under a specific device UUID. Used when
/// the client presents a known `device_id` whose hardware fingerprint has
/// changed (component swap) — same logical device, new hardware.
async fn find_active_by_device_id(
    pool: &PgPool,
    device_id: uuid::Uuid,
) -> Result<Option<(uuid::Uuid, String)>, SeatError> {
    sqlx::query_as(
        "SELECT device_id, db_role FROM client_devices \
         WHERE device_id = $1 AND revoked_at IS NULL \
         LIMIT 1",
    )
    .bind(device_id)
    .fetch_optional(pool)
    .await
    .map_err(|e| SeatError::Other(format!("find seat by device_id: {}", e)))
}

/// Rotate the seat's password and refresh its registry row. Shared by the
/// re-pair (fingerprint match) and hardware-swap (device_id match) paths.
async fn reuse_seat(
    pool: &PgPool,
    device_id: uuid::Uuid,
    db_role: &str,
    req: &SeatRequest<'_>,
) -> Result<ProvisionedSeat, SeatError> {
    let password = generate_password();
    upsert_client_role(pool, db_role, &password).await?;
    // Refresh identity/registry metadata. Fingerprint is written back
    // unconditionally: a no-op on plain re-pair, the update that adopts the
    // new hardware hash on a component swap.
    sqlx::query(
        "UPDATE client_devices SET \
             last_seen = NOW(), \
             last_seen_ip = COALESCE($3::inet, last_seen_ip), \
             device_name = COALESCE(NULLIF($2, ''), device_name), \
             hardware_fingerprint = $4 \
         WHERE device_id = $1",
    )
    .bind(device_id)
    .bind(req.device_name.trim())
    .bind(req.peer_ip.map(|ip| ip.to_string()))
    .bind(req.device_fingerprint.trim())
    .execute(pool)
    .await
    .map_err(|e| SeatError::Other(format!("refresh seat registry row: {}", e)))?;
    Ok(ProvisionedSeat {
        db_role: db_role.to_string(),
        db_password: password,
        device_id: device_id.to_string(),
    })
}

/// Provision (or reclaim) the database seat for one client device.
///
/// Called by the TLS pairing listener after the single-use pairing code has
/// been consumed. Three outcomes, checked in order:
///
///   * **Case A — fingerprint match (re-pair):** the existing active seat is
///     reclaimed: password rotated, `last_seen` refreshed, the SAME
///     `device_id` is returned. Consumes no additional seat (NFR-31).
///   * **Case B — device_id match (same logical device, changed hardware):**
///     reclaimed as in Case A, with the registry fingerprint updated to the
///     new value. Consumes no additional seat.
///   * **Case C — brand-new device:** the signed `max_client_devices` cap is
///     enforced (`u32::MAX` = unlimited, the legacy v1-license resolution),
///     then a fresh per-device role + registry row are created.
///
/// `SEAT-PREREQ`: a request with no usable identity (empty fingerprint, or a
/// `device_id` that is not a valid UUID — the registry column is `UUID`) is
/// rejected BEFORE any seat is counted or created: a device that cannot be
/// uniquely identified cannot be counted against the vendor cap, reclaimed on
/// re-pair, or revoked.
pub async fn provision_client_seat(
    pool: &PgPool,
    req: SeatRequest<'_>,
    max_client_devices: u32,
) -> Result<ProvisionedSeat, SeatError> {
    // ── SEAT-PREREQ: identity validation ──────────────────────────────────
    let fingerprint = req.device_fingerprint.trim();
    if fingerprint.is_empty() {
        return Err(SeatError::Other(
            "SEAT-PREREQ: pairing request carried no hardware fingerprint".to_string(),
        ));
    }
    let device_id = uuid::Uuid::parse_str(req.device_id.trim()).map_err(|_| {
        SeatError::Other(format!(
            "SEAT-PREREQ: device_id is not a valid UUID: {:?}",
            req.device_id
        ))
    })?;

    ensure_base_role(pool).await?;

    // ── Case A: this hardware already holds an active seat ────────────────
    if let Some((existing_id, db_role)) = find_active_by_fingerprint(pool, fingerprint).await? {
        return reuse_seat(pool, existing_id, &db_role, &req).await;
    }

    // ── Case B: this device_id already holds an active seat ───────────────
    if let Some((existing_id, db_role)) = find_active_by_device_id(pool, device_id).await? {
        return reuse_seat(pool, existing_id, &db_role, &req).await;
    }

    // ── Case C: brand-new seat — enforce the signed cap ───────────────────
    if max_client_devices != u32::MAX {
        let active = active_seat_count(pool).await?;
        if active >= max_client_devices as i64 {
            return Err(SeatError::Exhausted {
                active,
                max: max_client_devices,
            });
        }
    }

    let db_role = sanitize_device_role(&device_id.to_string())?;
    let password = generate_password();
    upsert_client_role(pool, &db_role, &password).await?;

    let device_name = {
        let n = req.device_name.trim();
        if n.is_empty() {
            "Unnamed device"
        } else {
            n
        }
    };
    sqlx::query(
        "INSERT INTO client_devices \
             (device_id, device_name, hardware_fingerprint, db_role, last_seen, last_seen_ip) \
         VALUES ($1, $2, $3, $4, NOW(), $5::inet)",
    )
    .bind(device_id)
    .bind(device_name)
    .bind(fingerprint)
    .bind(&db_role)
    .bind(req.peer_ip.map(|ip| ip.to_string()))
    .execute(pool)
    .await
    .map_err(|e| SeatError::Other(format!("register seat row: {}", e)))?;

    Ok(ProvisionedSeat {
        db_role,
        db_password: password,
        device_id: device_id.to_string(),
    })
}

/// Revoke a seat: stamp `revoked_at`/`revoked_by` and flip the role to
/// `NOLOGIN` so the workstation can no longer authenticate to PostgreSQL.
/// (`NOLOGIN` blocks every NEW connection at login time — including those of
/// a still-running client app's connection pool.)
///
/// Idempotent: revoking an unknown or already-revoked device is a no-op
/// success, so a Settings-UI retry can never fail destructively.
#[allow(dead_code)] // exercised by tests/client_seat_tests.rs; IPC surface pending
pub async fn revoke_seat(
    pool: &PgPool,
    device_id: uuid::Uuid,
    revoked_by: Option<&str>,
) -> Result<(), SeatError> {
    let row: Option<(String,)> = sqlx::query_as(
        "UPDATE client_devices SET revoked_at = NOW(), revoked_by = $2 \
         WHERE device_id = $1 AND revoked_at IS NULL RETURNING db_role",
    )
    .bind(device_id)
    .bind(revoked_by)
    .fetch_optional(pool)
    .await
    .map_err(|e| SeatError::Other(format!("revoke seat: {}", e)))?;

    let Some((db_role,)) = row else {
        return Ok(()); // unknown or already revoked — idempotent no-op
    };

    crate::db::validate_db_identifier(&db_role).map_err(SeatError::Other)?;
    sqlx::query(&format!("ALTER ROLE \"{db_role}\" NOLOGIN"))
        .execute(pool)
        .await
        .map_err(|e| SeatError::Other(format!("revoke seat (disable login): {}", e)))?;
    Ok(())
}

/// Tauri command: revoke a client device seat.
///
/// Flips the device's DB role to `NOLOGIN` and stamps the registry row with
/// `revoked_at` / `revoked_by`. Idempotent — revoking an unknown or already
/// revoked device is a no-op success.
///
/// The pool is resolved from Tauri app state (the pairing listener starts
/// before `db::initialize` manages the pool, so it cannot be captured at
/// startup). This is the IPC surface for `revoke_seat` — previously pending.
#[cfg(feature = "server-build")]
#[tauri::command]
pub async fn revoke_seat_command(
    app_handle: tauri::AppHandle,
    device_id: String,
) -> Result<(), String> {
    let pool = app_handle
        .try_state::<sqlx::PgPool>()
        .ok_or_else(|| "database pool not available".to_string())?;

    let device_uuid = Uuid::parse_str(&device_id).map_err(|e| format!("invalid device_id: {e}"))?;

    revoke_seat(pool, device_uuid, None)
        .await
        .map_err(|e| format!("revoke seat: {e}"))?;

    Ok(())
}
